function slideHayInit() {
  if (SLIDES._hay) return;
  SLIDES._hay = SLIDES.map(s => (s[2] + ' ' + s[3]).toLowerCase());
  SLIDES._tl = SLIDES.map(s => s[2].toLowerCase());
}
function termVariants(t) {
  const v = new Set([t]);
  (SLIDE_ALIASES[t] || []).forEach(x => v.add(x));
  if (t.length > 4) {
    if (t.endsWith('ices')) v.add(t.slice(0, -4) + 'ix');
    else if (t.endsWith('ies')) v.add(t.slice(0, -3) + 'y');
    else if (t.endsWith('es')) v.add(t.slice(0, -2));
    else if (t.endsWith('s')) v.add(t.slice(0, -1));
  }
  return [...v].filter(Boolean);
}
function countOcc(hay, w) { let n = 0, i = hay.indexOf(w); while (i >= 0 && n < 6) { n++; i = hay.indexOf(w, i + w.length); } return n; }

function searchSlides(q, scope) {
  slideHayInit();
  const query = q.toLowerCase().trim();
  const whole = SLIDE_ALIASES[query.replace(/\s+/g, '')] ? termVariants(query.replace(/\s+/g, '')) : [query];
  const terms = query.split(/[\s,;/]+/).filter(Boolean).map(termVariants);
  const res = [];
  SLIDES.forEach((s, i) => {
    const f = SLIDE_FILES[s[0]];
    if (scope === 'lec' && f.order > 10) return;
    if (scope === 'tut' && f.order <= 10) return;
    const hay = SLIDES._hay[i], tl = SLIDES._tl[i];
    let score = 0, hit = 0;
    for (const vs of terms) {
      let best = 0;
      for (const w of vs) { const c = countOcc(hay, w); if (c) best = Math.max(best, Math.min(c, 5) + (tl.includes(w) ? 6 : 0) + (w.includes(' ') ? 2 : 0)); }
      if (best) { hit++; score += best; }
    }
    if (!hit) return;
    for (const w of whole) if (w.includes(' ') || terms.length > 1) { if (tl.includes(w)) score += 12; else if (hay.includes(w)) score += 8; }
    if (/^(outline|course contents|summary|recap|summary of lec)/.test(tl)) score *= 0.4; // overview slides list every topic
    res.push({ i, score, all: hit === terms.length });
  });
  const strict = res.filter(r => r.all);
  const list = (strict.length ? strict : res).sort((a, b) => b.score - a.score || SLIDE_FILES[SLIDES[a.i][0]].order - SLIDE_FILES[SLIDES[b.i][0]].order || SLIDES[a.i][1] - SLIDES[b.i][1]);
  return { list, partial: !strict.length && res.length > 0, words: [...new Set(terms.flat())].sort((a, b) => b.length - a.length) };
}

function slideSnippet(text, words) {
  const low = text.toLowerCase();
  let at = -1;
  for (const w of words) { at = low.indexOf(w); if (at >= 0) break; }
  const start = Math.max(0, at - 70), piece = (start ? '… ' : '') + text.slice(start, start + 220) + (text.length > start + 220 ? ' …' : '');
  let html = esc(piece);
  for (const w of words) if (w.length > 1) html = html.replace(new RegExp(w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), m => `<mark>${m}</mark>`);
  return html;
}

let SLIDE_WIN = null;
function slideUrl(fi, page) { return '../' + encodeURIComponent(SLIDE_FILES[fi].name) + '#page=' + page; }
function openSlide(fi, page) {
  // close the previous viewer first: PDF viewers ignore a #page change on an already-open file
  try { if (SLIDE_WIN && !SLIDE_WIN.closed) SLIDE_WIN.close(); } catch (e) { /* ignore */ }
  const w = Math.min(1100, Math.round(screen.availWidth * 0.55)), hgt = Math.round(screen.availHeight * 0.9);
  SLIDE_WIN = window.open(slideUrl(fi, page), 'ee2211slide', `width=${w},height=${hgt},left=${screen.availWidth - w},top=0`);
  if (!SLIDE_WIN) location.href = slideUrl(fi, page); // pop-up blocked → open here
}
function slideCard(i, words) {
  const s = SLIDES[i], f = SLIDE_FILES[s[0]];
  return `<button class="slcard" onclick="openSlide(${s[0]}, ${s[1]})" title="Open ${esc(f.name)} at page ${s[1]} in a new window">` +
    `<img loading="lazy" alt="" src="data:image/jpeg;base64,${SLIDE_THUMBS[i]}">` +
    `<span class="slmeta"><b>${esc(f.label.split(' — ')[0])}</b> · slide ${s[1]} / ${f.pages}</span>` +
    `<span class="sltitle">${esc(s[2] || '(no title)')}</span>` +
    (words ? `<span class="slsnip">${slideSnippet(s[3], words)}</span>` : '') + '</button>';
}

tool({
  id: 'slides', cat: 'slides', name: 'Lecture Slide Finder — concept keyword → slide (개념 → 슬라이드)', short: 'Slide Finder',
  kw: 'slide lecture pdf concept keyword find page 슬라이드 강의 개념 찾기 tutorial',
  live: true, solveLabel: 'Search',
  desc: '개념 키워드를 입력하면 그 개념이 나오는 강의/튜토리얼 슬라이드를 찾아줍니다. 카드를 누르면 <b>그 PDF의 해당 페이지가 옆에 새 창</b>으로 열려요. ' +
    '영어, 한국어(예: 역행렬, 분산), 축약어(예: Mean Squared Error (MSE), Probability Mass Function (PMF)) 모두 됩니다. 비우면 강의별 목차가 나와요.',
  inputs: [
    { k: 'q', type: 'text', label: '개념 키워드 (concept keyword)', def: 'left inverse', ph: 'for example: ridge, over-determined, 역행렬, bayes, one-hot', wide: true },
    { k: 'scope', type: 'select', label: '범위 (scope)', def: 'all', options: [['all', 'Lectures + Tutorials'], ['lec', 'Lectures only'], ['tut', 'Tutorials only']] },
  ],
  solve(v, R) {
    if (typeof SLIDES === 'undefined' || !SLIDES.length) uerr('Slide index is missing — run  python3 build_slides.py  then  python3 build.py');
    const q = String(v.q || '').trim();
    if (!q) {
      const html = SLIDE_FILES.map((f, fi) => {
        if ((v.scope === 'lec' && f.order > 10) || (v.scope === 'tut' && f.order <= 10)) return '';
        let prev = '';
        const rows = SLIDES.map((s, i) => [s, i]).filter(([s]) => s[0] === fi).filter(([s]) => { const t = s[2]; const keep = t && t !== prev; prev = t; return keep; })
          .map(([s]) => `<li><a href="javascript:void 0" onclick="openSlide(${fi}, ${s[1]})"><span class="muted">p${s[1]}</span> ${esc(s[2])}</a></li>`).join('');
        return `<details class="sltoc"><summary>${esc(f.label)} <span class="muted">(${f.pages} slides)</span></summary><ul>${rows}</ul></details>`;
      }).join('');
      R.raw(`<div class="slnote">키워드를 입력하거나, 아래 강의별 목차에서 바로 고르세요.</div>${html}`);
      return;
    }
    const { list, partial, words } = searchSlides(q, v.scope);
    if (!list.length) {
      R.raw(`<div class="note warn big">“${esc(q)}” 이(가) 들어간 슬라이드가 없어요. 다른 단어(영어 원문 표현)로 검색하거나 단어 수를 줄여보세요.</div>`);
      return;
    }
    const top = list.slice(0, 40);
    R.raw(`<div class="slnote"><b>${list.length}</b> slide${list.length > 1 ? 's' : ''} found${partial ? ' (일부 단어만 일치)' : ''} — 카드를 누르면 PDF 해당 페이지가 새 창으로 열립니다.${list.length > 40 ? ' 상위 40개만 표시.' : ''}</div>` +
      `<div class="slgrid">${top.map(r => slideCard(r.i, words)).join('')}</div>`);
  },
});

